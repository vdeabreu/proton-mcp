# --- IMAP modified UTF-7 (RFC 3501 §5.1.3), needed for non-ASCII folder names ---

def _decode_mutf7(name: str) -> str:
    def repl(m: re.Match) -> str:
        chunk = m.group(1)
        if chunk == "":
            return "&"
        b64 = chunk.replace(",", "/")
        b64 += "=" * (-len(b64) % 4)
        return base64.b64decode(b64).decode("utf-16-be")

    return re.sub(r"&([^-]*)-", repl, name)


def _encode_mutf7(name: str) -> str:
    out, buf = [], []

    def flush():
        if buf:
            raw = "".join(buf).encode("utf-16-be")
            out.append("&" + base64.b64encode(raw).decode().rstrip("=").replace("/", ",") + "-")
            buf.clear()

    for ch in name:
        if 0x20 <= ord(ch) <= 0x7E:
            flush()
            out.append("&-" if ch == "&" else ch)
        else:
            buf.append(ch)
    flush()
    return "".join(out)


def _quote(mailbox: str) -> str:
    encoded = _encode_mutf7(_clean("folder", mailbox)).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{encoded}"'


_CONTROL_RE = re.compile(r"[\x00-\x1f\x7f]")


def _clean(field: str, value: str) -> str:
    """Reject control characters in text that goes into an IMAP command.

    imaplib sends arguments as-is: a CR/LF inside a quoted search term would end
    the command and let the rest run as new IMAP commands (SELECT, MOVE, DELETE…),
    which a prompt-injected model could be steered into.
    """
    if _CONTROL_RE.search(value):
        raise ToolError(f"{field} must not contain control characters (line breaks, tabs...)")
    return value


# --- connection ---

def _ensure_loopback(host: str) -> None:
    # Bridge uses a self-signed certificate, so TLS verification is disabled:
    # only acceptable when the traffic never leaves this machine.
    try:
        ok = host == "localhost" or ipaddress.ip_address(host).is_loopback
    except ValueError:
        ok = False
    if not ok:
        raise ToolError(f"PROTON_IMAP_HOST must be a loopback address, got {host!r}")


def _credentials() -> tuple[str, str]:
    user = os.environ.get("PROTON_BRIDGE_USER")
    password = os.environ.get("PROTON_BRIDGE_PASSWORD")
    if not user or not password:
        raise ToolError("PROTON_BRIDGE_USER and PROTON_BRIDGE_PASSWORD must be set")
    _ensure_loopback(HOST)
    return user, password


def _bridge_tls() -> ssl.SSLContext:
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    return ctx


@contextlib.contextmanager
def _imap():
    user, password = _credentials()
    ctx = _bridge_tls()

    try:
        if SECURITY == "ssl":
            conn = imaplib.IMAP4_SSL(HOST, PORT, ssl_context=ctx, timeout=30)
        else:
            conn = imaplib.IMAP4(HOST, PORT, timeout=30)
            conn.starttls(ssl_context=ctx)
    except (OSError, imaplib.IMAP4.error) as exc:
        raise ToolError(f"Cannot reach Proton Mail Bridge on {HOST}:{PORT} ({exc}). Is Bridge running?") from exc
    try:
        try:
            conn.login(user, password)
        except imaplib.IMAP4.error as exc:
            raise ToolError(f"Bridge rejected the login: {exc}. Check the Bridge IMAP password.") from exc
        yield conn
    finally:
        with contextlib.suppress(Exception):
            conn.logout()


def _examine(conn: imaplib.IMAP4, folder: str) -> None:
    typ, data = conn.select(_quote(folder), readonly=True)
    if typ != "OK":
        raise ToolError(f"Cannot open folder {folder!r}: {data}")


# --- message parsing ---

_VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
_HIDDEN_STYLE_RE = re.compile(r"display\s*:\s*none|visibility\s*:\s*hidden|font-size\s*:\s*0(?![.\d])|"
                              r"max-height\s*:\s*0(?![.\d])|opacity\s*:\s*0(?![.\d])", re.I)


class _TextExtractor(HTMLParser):
    """HTML to text, dropping scripts, styles and elements hidden from the reader.

    Hidden text (display:none, font-size:0…) is a common way to slip instructions
    to an AI that the human never sees. This catches the usual tricks, not all of
    them (white-on-white text, off-screen positioning, CSS classes).
    """

    def __init__(self):
        super().__init__()
        self.parts: list[str] = []
        self._skip_tag: str | None = None  # tag that opened the skipped subtree
        self._skip_depth = 0  # nesting of that same tag name inside it

    def handle_starttag(self, tag, attrs):
        if self._skip_tag == "head" and tag == "body":
            self._skip_tag = None  # tolerate a missing </head>
        if self._skip_tag:
            if tag == self._skip_tag:
                self._skip_depth += 1
            return
        attributes = dict(attrs)
        hidden = (
            tag in ("script", "style", "head", "title", "template")
            or "hidden" in attributes
            or bool(_HIDDEN_STYLE_RE.search(attributes.get("style") or ""))
        )
        if hidden:
            if tag not in _VOID_TAGS:
                self._skip_tag, self._skip_depth = tag, 1
            return
        if tag in ("br", "p", "div", "tr", "li", "h1", "h2", "h3"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if self._skip_tag and tag == self._skip_tag:
            self._skip_depth -= 1
            if self._skip_depth == 0:
                self._skip_tag = None

    def handle_data(self, data):
        if not self._skip_tag:
            self.parts.append(data)


def _html_to_text(html: str) -> str:
    parser = _TextExtractor()
    parser.feed(html)
    text = "".join(parser.parts)
    return re.sub(r"\n\s*\n\s*\n+", "\n\n", text).strip()


def _body_text(msg: email.message.EmailMessage) -> str:
    part = msg.get_body(preferencelist=("plain", "html"))
    if part is None:
        return ""
    content = part.get_content()
    return _html_to_text(content) if part.get_content_type() == "text/html" else content.strip()


def _attachments(msg: email.message.EmailMessage) -> list[dict]:
    return [
        {
            "filename": part.get_filename(),
            "content_type": part.get_content_type(),
            "size": len(part.get_payload(decode=True) or b""),
        }
        for part in msg.iter_attachments()
    ]


def _date_iso(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return parsedate_to_datetime(value).isoformat()
    except (TypeError, ValueError):
        return value


def _fetch_summaries(conn: imaplib.IMAP4, uids: list[bytes]) -> list[dict]:
    if not uids:
        return []
    typ, data = conn.uid(
        "FETCH", b",".join(uids),
        "(UID FLAGS RFC822.SIZE BODY.PEEK[HEADER.FIELDS (FROM TO SUBJECT DATE)])",
    )
    if typ != "OK":
        raise ToolError(f"FETCH failed: {data}")
    out = []
    for item in data:
        if not isinstance(item, tuple):
            continue
        meta = item[0].decode(errors="replace")
        uid = re.search(r"UID (\d+)", meta)
        flags = re.search(r"FLAGS \(([^)]*)\)", meta)
        size = re.search(r"RFC822\.SIZE (\d+)", meta)
        headers = email.message_from_bytes(item[1], policy=email.policy.default)
        out.append({
            "uid": int(uid.group(1)) if uid else None,
            "date": _date_iso(headers.get("Date")),
            "from": str(headers.get("From", "")),
            "to": str(headers.get("To", "")),
            "subject": str(headers.get("Subject", "")),
            "unread": "\\Seen" not in (flags.group(1) if flags else ""),
            "size": int(size.group(1)) if size else None,
        })
    order = {int(u): i for i, u in enumerate(uids)}
    out.sort(key=lambda m: order.get(m["uid"], len(order)))
    return out


def _latest_uids(conn: imaplib.IMAP4, uids: list[bytes], limit: int) -> list[bytes]:
    """Return the `limit` most recent uids, newest first.

    Bridge assigns UIDs in sync order, not date order, so sort on INTERNALDATE.
    """
    if not uids:
        return []
    typ, data = conn.uid("FETCH", b",".join(uids), "(UID INTERNALDATE)")
    if typ != "OK":
        raise ToolError(f"FETCH failed: {data}")
    dated = []
    for item in data:
        line = item[0] if isinstance(item, tuple) else item
        if not isinstance(line, bytes):
            continue
        uid = re.search(rb"UID (\d+)", line)
        when = imaplib.Internaldate2tuple(line)
        if uid:
            dated.append((time.mktime(when) if when else 0, uid.group(1)))
    dated.sort(reverse=True)
    return [uid for _, uid in dated[:limit]]


def _imap_date(iso: str) -> str:
    d = date.fromisoformat(iso)
    return f"{d.day:02d}-{d.strftime('%b')}-{d.year}"


# --- tools ---

@mcp.tool(annotations=READ_ONLY)
def list_folders() -> list[str]:
    """List every folder and label of the mailbox (labels appear as 'Labels/<name>', folders as 'Folders/<name>')."""
    with _imap() as conn:
        typ, data = conn.list()
        if typ != "OK":
            raise ToolError(f"LIST failed: {data}")
        names = []
        for line in data:
            if not line:
                continue
            m = re.match(rb'\((?P<flags>[^)]*)\) (?P<delim>"[^"]*"|NIL) (?P<name>.+)', line)
            if not m:
                continue
            name = m.group("name").decode()
            if name.startswith('"') and name.endswith('"'):
                name = name[1:-1].replace('\\"', '"').replace("\\\\", "\\")
            names.append(_decode_mutf7(name))
        return names


@mcp.tool(annotations=READ_ONLY)
def list_emails(folder: str = "INBOX", limit: int = 20, unread_only: bool = False) -> list[dict]:
    """List the most recent emails of a folder, newest first (headers only)."""
    limit = max(1, min(limit, 100))
    with _imap() as conn:
        _examine(conn, folder)
        typ, data = conn.uid("SEARCH", "UNSEEN" if unread_only else "ALL")
        if typ != "OK":
            raise ToolError(f"SEARCH failed: {data}")
        uids = _latest_uids(conn, data[0].split(), limit)
        return _fetch_summaries(conn, uids)


@mcp.tool(annotations=READ_ONLY)
def search_emails(
    folder: str = "All Mail",
    from_: str | None = None,
    to: str | None = None,
    subject: str | None = None,
    text: str | None = None,
    since: str | None = None,
    before: str | None = None,
    unread_only: bool = False,
    limit: int = 20,
) -> list[dict]:
    """Search emails in a folder, newest first (headers only).

    from_/to/subject/text are case-insensitive substring matches (text searches headers and body).
    since/before are ISO dates (YYYY-MM-DD); before is exclusive.
    The default folder 'All Mail' covers the whole mailbox.
    """
    limit = max(1, min(limit, 100))
    criteria: list[str] = []
    non_ascii: list[tuple[str, str]] = []
    for key, value in (("FROM", from_), ("TO", to), ("SUBJECT", subject), ("TEXT", text)):
        if not value:
            continue
        _clean(key.lower(), value)
        if value.isascii():
            criteria += [key, '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"']
        else:
            non_ascii.append((key, value))
    if len(non_ascii) > 1:
        raise ToolError("Only one search field may contain non-ASCII characters at a time")
    if since:
        criteria += ["SINCE", _imap_date(since)]
    if before:
        criteria += ["BEFORE", _imap_date(before)]
    if unread_only:
        criteria.append("UNSEEN")

    with _imap() as conn:
        _examine(conn, folder)
        if non_ascii:
            # imaplib sends conn.literal right after the last argument,
            # so the criterion that owns it goes last.
            key, value = non_ascii[0]
            conn.literal = value.encode()
            typ, data = conn.uid("SEARCH", "CHARSET", "UTF-8", *criteria, key)
        else:
            typ, data = conn.uid("SEARCH", *(criteria or ["ALL"]))
        if typ != "OK":
            raise ToolError(f"SEARCH failed: {data}")
        uids = _latest_uids(conn, data[0].split(), limit)
        return _fetch_summaries(conn, uids)


@mcp.tool(annotations=READ_ONLY)
def read_email(uid: int, folder: str = "INBOX", max_chars: int = 20000) -> dict:
    """Read one email by its uid (from list_emails/search_emails, in the same folder). Does not mark it as read."""
    with _imap() as conn:
        _examine(conn, folder)
        typ, data = conn.uid("FETCH", str(uid), "(BODY.PEEK[])")
        if typ != "OK" or not data or not isinstance(data[0], tuple):
            raise ToolError(f"Email uid {uid} not found in {folder!r}")
        msg = email.message_from_bytes(data[0][1], policy=email.policy.default)
    body = _body_text(msg)
    truncated = len(body) > max_chars
    return {
        "uid": uid,
        "folder": folder,
        "date": _date_iso(msg.get("Date")),
        "from": str(msg.get("From", "")),
        "to": str(msg.get("To", "")),
        "cc": str(msg.get("Cc", "")),
        "subject": str(msg.get("Subject", "")),
        "message_id": msg.get("Message-ID"),
        "attachments": _attachments(msg),
        "body": body[:max_chars],
        "truncated": truncated,
    }


@contextlib.contextmanager
def _smtp():
    user, password = _credentials()
    ctx = _bridge_tls()
    try:
        if SMTP_SECURITY == "ssl":
            conn = smtplib.SMTP_SSL(HOST, SMTP_PORT, context=ctx, timeout=30)
        else:
            conn = smtplib.SMTP(HOST, SMTP_PORT, timeout=30)
            conn.starttls(context=ctx)
    except (OSError, smtplib.SMTPException) as exc:
        raise ToolError(f"Cannot reach Bridge SMTP on {HOST}:{SMTP_PORT} ({exc}). Is Bridge running?") from exc
    try:
        try:
            conn.login(user, password)
        except smtplib.SMTPException as exc:
            raise ToolError(f"Bridge rejected the SMTP login: {exc}") from exc
        yield conn
    finally:
        with contextlib.suppress(Exception):
            conn.quit()


def _addresses(field: str, value: str | None) -> list[str]:
    if not value:
        return []
    pairs = getaddresses([value])
    bad = [addr for _, addr in pairs if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", addr)]
    if bad or not pairs:
        raise ToolError(f"Invalid address in {field}: {value!r}")
    return [addr for _, addr in pairs]


# --- Light Markdown -> HTML for outgoing mail ---
# Supported: blank line = paragraph, single newline = line break, "- " / "* " bullets,
# "1. " numbered lists, **bold**, *italic*, [text](https://url), bare URLs.

_LINK_RE = re.compile(r"\[([^\]\n]+)\]\((https?://[^\s)]+|mailto:[^\s)]+)\)")
_BARE_URL_RE = re.compile(r"(?<![\"'=>])\bhttps?://[^\s<]+[^\s<.,;:!?)\]]")
_BULLET_RE = re.compile(r"^\s*[-*•]\s+(.*)$")
_NUMBER_RE = re.compile(r"^\s*\d+[.)]\s+(.*)$")


def _inline_html(text: str) -> str:
    import html as _html

    links: list[str] = []

    def stash(label: str, url: str) -> str:
        links.append(
            f'<a href="{_html.escape(url, quote=True)}" style="color:#6d4aff">'
            f"{_html.escape(label)}</a>"
        )
        return f"\x00{len(links) - 1}\x00"

    text = _LINK_RE.sub(lambda m: stash(m.group(1), m.group(2)), text)
    text = _BARE_URL_RE.sub(lambda m: stash(m.group(0), m.group(0)), text)
    text = _html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: links[int(m.group(1))], text)


def _markdown_to_html(body: str) -> str:
    blocks = re.split(r"\n\s*\n", body.replace("\r\n", "\n").strip())
    out = []
    for block in blocks:
        # Split the block into runs of same-kind lines (text / bullets / numbers),
        # so "Intro :\n- a\n- b" renders as a paragraph followed by a list.
        runs: list[tuple[str, list[str]]] = []
        for line in block.split("\n"):
            if m := _BULLET_RE.match(line):
                kind, content = "ul", m.group(1)
            elif m := _NUMBER_RE.match(line):
                kind, content = "ol", m.group(1)
            else:
                kind, content = "p", line
            if runs and runs[-1][0] == kind:
                runs[-1][1].append(content)
            else:
                runs.append((kind, [content]))
        for i, (kind, lines) in enumerate(runs):
            last = i == len(runs) - 1
            margin = "0 0 14px 0" if last else "0 0 6px 0"
            if kind == "p":
                out.append(
                    f'<p style="margin:{margin}">' + "<br>".join(_inline_html(l) for l in lines) + "</p>"
                )
            else:
                items = "".join(f"<li>{_inline_html(l)}</li>" for l in lines)
                out.append(f'<{kind} style="margin:{margin};padding-left:22px">{items}</{kind}>')
    return (
        '<!DOCTYPE html><html><head><meta charset="utf-8"></head><body>'
        '<div style="font-family:Arial,Helvetica,sans-serif;font-size:14px;line-height:1.5;color:#1c1b22">'
        + "".join(out)
        + "</div></body></html>"
    )


def _markdown_to_plain(body: str) -> str:
    text = _LINK_RE.sub(lambda m: f"{m.group(1)} ({m.group(2).removeprefix('mailto:')})", body)
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", text)
    return text


_QUOTE_LANG = os.environ.get("PROTON_QUOTE_LANG", "en").strip().lower()
_ATTRIBUTION = {
    # lang: (weekdays, months, "when" format, "wrote" suffix, unknown sender)
    "en": (
        ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"],
        ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
        "On {wd}, {mon} {day}, {year} at {hm}, ", "wrote:", "Unknown sender",
    ),
    "fr": (
        ["lun.", "mar.", "mer.", "jeu.", "ven.", "sam.", "dim."],
        ["janv.", "févr.", "mars", "avr.", "mai", "juin",
         "juil.", "août", "sept.", "oct.", "nov.", "déc."],
        "Le {wd} {day} {mon} {year} à {hm}, ", "a écrit :", "Expéditeur inconnu",
    ),
}


def _attribution(original: email.message.EmailMessage, lang: str | None = None) -> str:
    """'On Mon, Nov 9, 2026 at 12:13, Alice Martin <alice@example.com> wrote:'

    Language from PROTON_QUOTE_LANG (en, fr); the time is shown in local time.
    """
    weekdays, months, when_fmt, wrote, unknown = _ATTRIBUTION.get(lang or _QUOTE_LANG, _ATTRIBUTION["en"])
    who = str(original.get("From") or "").strip() or unknown
    try:
        d = parsedate_to_datetime(original["Date"]).astimezone()
        when = when_fmt.format(wd=weekdays[d.weekday()], mon=months[d.month - 1],
                               day=d.day, year=d.year, hm=f"{d:%H:%M}")
    except (TypeError, ValueError, KeyError, AttributeError):
        when = ""
    line = f"{when}{who} {wrote}"
    return line[0].upper() + line[1:]


def _quote_original(original: email.message.EmailMessage) -> tuple[str, str]:
    """Return (plain, html) quoted versions of the original message, Proton-style."""
    import html as _html

    header = _attribution(original)
    text = _body_text(original).replace("\r\n", "\n")
    plain = f"\n\n{header}\n" + "\n".join(("> " + l) if l else ">" for l in text.split("\n"))
    quoted = "<br>".join(_html.escape(l, quote=False) for l in text.split("\n"))
    html_part = (
        f'<div style="margin:18px 0 6px 0;color:#5c5b66">{_html.escape(header, quote=False)}</div>'
        '<blockquote style="margin:0 0 0 4px;padding:0 0 0 10px;border-left:3px solid #d1cfd9;'
        f'color:#5c5b66">{quoted}</blockquote>'
    )
    return plain, html_part


# --- sender display name ---
#
# Bridge sends the From header exactly as given: unlike Proton's web and mobile
# apps, it does not add the display name set in Proton's settings, and IMAP has
# no way to read that setting. Desktop clients (Thunderbird, Apple Mail) ask for
# "your name" at setup for the same reason. Here it comes from PROTON_SENDER_NAME,
# or else from the From header of your recent messages in Sent.

SENT_FOLDER = "Sent"
_SENT_SCAN = 300
_sent_from_cache: list[str] = []  # From headers of recent Sent messages, filled once


def _valid_name(name: str | None) -> str | None:
    name = (name or "").strip()
    if not name or len(name) > 100 or _CONTROL_RE.search(name) or "@" in name:
        return None
    return name


def _pick_sender_name(from_headers: list[str], own_address: str) -> str | None:
    """Most frequent display name on the user's own address, else on any address in Sent."""
    own, other = {}, {}
    for header in from_headers:
        name, addr = parseaddr(header)
        name = _valid_name(name)
        if name:
            bucket = own if addr.lower() == own_address.lower() else other
            bucket[name] = bucket.get(name, 0) + 1
    for bucket in (own, other):
        if bucket:
            return max(bucket, key=bucket.get)
    return None


def _sent_from_headers() -> list[str]:
    """From headers of the most recent messages in Sent (cached; [] if Bridge can't be read)."""
    if not _sent_from_cache:
        try:
            with _imap() as conn:
                _examine(conn, SENT_FOLDER)
                typ, data = conn.uid("SEARCH", None, "ALL")
                uids = data[0].split()[-_SENT_SCAN:] if typ == "OK" and data and data[0] else []
                headers = []
                if uids:
                    typ, resp = conn.uid("FETCH", b",".join(uids).decode(), "(BODY.PEEK[HEADER.FIELDS (FROM)])")
                    for part in resp if typ == "OK" else []:
                        if isinstance(part, tuple):
                            headers.append(str(email.message_from_bytes(part[1], policy=email.policy.default)["From"]))
            _sent_from_cache.extend(headers)
        except (ToolError, imaplib.IMAP4.error, OSError):
            return []  # don't block sending; try again next time
    return _sent_from_cache


def _sender_name(sender: str) -> str | None:
    configured = os.environ.get("PROTON_SENDER_NAME")
    if configured is not None:
        return _valid_name(configured)
    return _pick_sender_name(_sent_from_headers(), sender)


# --- sender addresses ---
#
# With Bridge in combined mode, one login covers every address of the account and
# Bridge accepts any MAIL FROM. So the server checks from_address itself, against
# the addresses known to be the user's: the Bridge login, PROTON_FROM_ADDRESSES,
# and the addresses the user has already sent from (Sent folder).

def _sender_addresses(login: str) -> list[str]:
    """The user's own addresses, the Bridge login first, then by how often they were used."""
    found = [login.lower()]
    for addr in _addresses("PROTON_FROM_ADDRESSES", os.environ.get("PROTON_FROM_ADDRESSES")):
        found.append(addr.lower())
    counts: dict[str, int] = {}
    for header in _sent_from_headers():
        addr = parseaddr(header)[1].lower()
        if addr and "@" in addr:
            counts[addr] = counts.get(addr, 0) + 1
    found += sorted(counts, key=counts.get, reverse=True)
    return list(dict.fromkeys(found))


def _reply_address(original: email.message.EmailMessage, own: list[str]) -> str | None:
    """The user's address the original was sent to, so replies go out from it (like Proton)."""
    fields = ("Delivered-To", "X-Original-To", "To", "Cc")
    values = [str(v) for f in fields for v in (original.get_all(f) or [])]
    for _, addr in getaddresses(values):
        if addr.lower() in own:
            return addr.lower()
    return None


def _choose_sender(login: str, from_address: str | None, original: email.message.EmailMessage | None) -> str:
    own = _sender_addresses(login)
    if from_address:
        if re.search(r"[\r\n\x00]", from_address):
            raise ToolError("from_address must be a single line (no line breaks)")
        addr = parseaddr(from_address)[1].lower()
        if addr not in own:
            raise ToolError(f"from_address must be one of your addresses: {', '.join(own)}")
        return addr
    if original is not None:
        return _reply_address(original, own) or login
    return login


def list_sender_addresses() -> list[dict]:
    """List the addresses send_email can send from, with the display name used for each.

    The first one is the default for new emails; replies default to the address
    the original email was sent to. Pass one as send_email's from_address.
    """
    login, _ = _credentials()
    return [
        {"address": addr, "name": _sender_name(addr), "default": i == 0}
        for i, addr in enumerate(_sender_addresses(login))
    ]


def _from_header(sender: str, name: str | None) -> Address | str:
    return Address(display_name=name, addr_spec=sender) if name else sender


def _build_message(
    sender: str, to: str, subject: str, body: str,
    cc: str | None, bcc: str | None, original: email.message.EmailMessage | None,
    include_original: bool = False, sender_name: str | None = None,
) -> tuple[EmailMessage, list[str]]:
    for field, value in (("subject", subject), ("to", to), ("cc", cc), ("bcc", bcc)):
        if value and re.search(r"[\r\n\x00]", value):
            raise ToolError(f"{field} must be a single line (no line breaks)")
    recipients = _addresses("to", to) + _addresses("cc", cc) + _addresses("bcc", bcc)
    if not _addresses("to", to):
        raise ToolError("At least one recipient is required in 'to'")

    msg = EmailMessage()
    msg["From"] = _from_header(sender, sender_name)
    msg["To"] = to
    if cc:
        msg["Cc"] = cc
    # Bcc goes in the SMTP envelope only, never in the headers.
    msg["Subject"] = subject
    msg["Date"] = formatdate(localtime=True)
    msg["Message-ID"] = make_msgid(domain=sender.rsplit("@", 1)[-1])
    if original is not None and original.get("Message-ID"):
        parent = original["Message-ID"].strip()
        refs = (original.get("References") or "").split()
        msg["In-Reply-To"] = parent
        msg["References"] = " ".join(refs + [parent])
    plain, html_body = _markdown_to_plain(body), _markdown_to_html(body)
    if original is not None and include_original:
        q_plain, q_html = _quote_original(original)
        plain += q_plain
        html_body = html_body.replace("</div></body>", q_html + "</div></body>", 1)
    msg.set_content(plain)
    msg.add_alternative(html_body, subtype="html")
    return msg, recipients


def send_email(
    to: str,
    subject: str,
    body: str,
    cc: str | None = None,
    bcc: str | None = None,
    reply_to_uid: int | None = None,
    reply_folder: str = "INBOX",
    include_original: bool = True,
    from_address: str | None = None,
) -> dict:
    """Send an email (HTML + plain-text alternative) from the user's Proton address. IRREVERSIBLE.

    Only call this after showing the user the exact sender, recipients, subject and
    body and receiving their explicit approval in chat.
    from_address picks which of the user's addresses sends it (see
    list_sender_addresses). If omitted, new emails go out from the default address
    and replies from the address the original was sent to.
    The body is light Markdown, rendered to HTML: blank line = new paragraph,
    single newline = line break, lines starting with "- " = bullet list,
    "1. " = numbered list, **bold**, *italic*, [text](https://url). Don't use
    headings, tables or raw HTML. Write the signature as the last paragraph.
    to/cc/bcc accept comma-separated addresses ("Name <a@b.c>, d@e.f").
    To reply, pass reply_to_uid (and reply_folder) of the original email: the reply
    is threaded with it. Write the subject yourself (e.g. "Re: <original subject>").
    Replies quote the original message below the body, like Proton does
    ("On <date>, <sender> wrote:" + quoted text); don't paste it into body
    yourself. Pass include_original=False to leave it out.
    A copy lands in the Sent folder automatically.
    """
    login, _ = _credentials()
    original = None
    if reply_to_uid is not None:
        with _imap() as conn:
            _examine(conn, reply_folder)
            typ, data = conn.uid(
                "FETCH", str(reply_to_uid), "(BODY.PEEK[])"
            )
            if typ != "OK" or not data or not isinstance(data[0], tuple):
                raise ToolError(f"Email uid {reply_to_uid} not found in {reply_folder!r}")
            original = email.message_from_bytes(data[0][1], policy=email.policy.default)

    sender = _choose_sender(login, from_address, original)
    msg, recipients = _build_message(
        sender, to, subject, body, cc, bcc, original, include_original, _sender_name(sender)
    )
    with _smtp() as conn:
        try:
            refused = conn.send_message(msg, from_addr=sender, to_addrs=recipients)
        except smtplib.SMTPException as exc:
            raise ToolError(f"Sending failed: {exc}") from exc
    return {
        "sent": True,
        "from": str(msg["From"]),
        "message_id": msg["Message-ID"],
        "to": to,
        "cc": cc,
        "bcc": bcc,
        "subject": subject,
        "refused_recipients": {k: v[1].decode(errors="replace") for k, v in refused.items()},
    }


if ENABLE_SEND:
    mcp.tool(annotations=READ_ONLY)(list_sender_addresses)
    mcp.tool(annotations=SENDS_MAIL)(send_email)


