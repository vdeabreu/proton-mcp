"""MCP server for Proton Mail, through a local Proton Mail Bridge (IMAP + SMTP).

Configuration (environment variables):
    PROTON_BRIDGE_USER      username shown by Bridge (your address)
    PROTON_BRIDGE_PASSWORD  password generated by Bridge (NOT your Proton password)
    PROTON_IMAP_HOST        default 127.0.0.1 (must be a loopback address, also used for SMTP)
    PROTON_IMAP_PORT        default 1143
    PROTON_IMAP_SECURITY    starttls (Bridge default) or ssl
    PROTON_SMTP_PORT        default 1025
    PROTON_SMTP_SECURITY    starttls (Bridge default) or ssl
    PROTON_QUOTE_LANG       language of the "On <date>, <sender> wrote:" line in replies: en (default) or fr
    PROTON_ENABLE_SEND      register send_email: true (default) or false
    PROTON_SENDER_NAME      display name in From ("Name <address>"); by default it is taken
                            from your recent messages in Sent (Proton's own apps set it)
    PROTON_FROM_ADDRESSES   extra addresses send_email may use as from_address (comma-separated);
                            the Bridge login and addresses found in Sent are always allowed

Every mailbox is opened with EXAMINE and bodies are fetched with BODY.PEEK,
so nothing is ever marked as read, moved or deleted. Text arguments that reach
IMAP are rejected if they contain control characters, so they can't smuggle
extra IMAP commands. The only write is send_email, flagged destructive so that
clients which honour the hint ask before each call.
"""

